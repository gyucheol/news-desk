def mark(text, phrases, w):
    spans = []
    for p in phrases:
        i = text.find(p)
        if i < 0: raise SystemExit(f'{w}: not found {p!r}')
        spans.append((i, i + len(p)))
    spans.sort()
    for a, b in zip(spans, spans[1:]):
        if a[1] > b[0]: raise SystemExit(f'{w}: overlap')
    for a, b in reversed(spans):
        text = text[:a] + '{{' + text[a:b] + '}}' + text[b:]
    return text

