def apply(page):
    for r, txt in zip(page['intro']['reading'], READING):
        r['means'] = txt
    assert len(READING) == len(page['intro']['reading'])
    byid = {n['id']: n for n in page['nodes']}
    for nid, ov in NODES.items():
        n = byid[nid]
        n['role'] = ov['role']
        n['bottleneck'] = ov['bottleneck']
        for i in sorted(ov.get('state_drop', []), reverse=True):
            del n['state'][i]
        assert len(ov['state']) == len(n['state']), nid
        for s, t in zip(n['state'], ov['state']):
            s['t'] = t
        names = {c['n']: c for c in n['companies']}
        for cname, note in ov.get('co', {}).items():
            assert cname in names, (nid, cname)
            names[cname]['note'] = note
    assert len(CYCLE_WHY) == len(page['cycle']['why'])
    for w, t in zip(page['cycle']['why'], CYCLE_WHY):
        w['t'] = t
    page['cycle']['next'] = CYCLE_NEXT
    return page
