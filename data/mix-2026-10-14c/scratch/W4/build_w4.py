HL = re.compile(r'\{\{([^{}]+)\}\}')
TAIL = re.compile(r' \((제목 기준|채널 전언)\)$')

def stat(s):
    plain = s.replace('{{', '').replace('}}', '')
    core = TAIL.sub('', plain)
    ms = HL.findall(s)
    h = sum(len(m) for m in ms)
    bad = [m for m in ms if m != m.strip() or len(m) > 30]
    rest = HL.sub('', s)
    return len(core), (h / len(core) if core else 0), bad, ('{' in rest or '}' in rest), core

