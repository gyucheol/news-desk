# 받아쓰기 낱말의 숫자·알파벳을 녹음에서 읽은 한글로 바꿈(자막 줄의 '읽은 말'과 글자로 맞추기 위해).
# 숫자 낱말이 줄 첫머리에 오면 글자 맞춤이 숫자 뒤 글자에서 시작해 자막 시작이 늦게 잡혔음('2016년' 줄이 1.1초 늦음).
# usage: ko_words.py in.json out.json
import json, sys
MAP = {'30': '삼십', '%': '퍼센트', '5': '오', '3가지를': '세가지를', '7년': '칠년', '1년': '일년', '3': '삼', '7만': '칠만', '8천': '팔천',
       '11시입니다.': '열한시입니다.', '2016년': '이천십육년', '28명에게': '스물여덟명에게', '28명': '스물여덟명', '26명이': '스물여섯명이',
       'A': '에이', 'B': '비', '1': '천이백', ',200달러를': '달러를', '92': '구십이', '%가': '퍼센트가', '1994년': '천구백구십사년',
       '80명에게': '여든명에게', '76': '칠십육', '%였습니다.': '퍼센트였습니다.', '64': '육십사'}
d = json.load(open(sys.argv[1]))
n = 0
for s in d:
    for w in s['words']:
        k = w[2].strip()
        if k in MAP:
            w[2] = ' ' + MAP[k]; n += 1
json.dump(d, open(sys.argv[2], 'w'), ensure_ascii=False, indent=1)
print(sys.argv[1], n, 'words changed')
